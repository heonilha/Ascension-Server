//! 게임 서버: 접속(세션), 방, 방 대응표. C++ 서버의 `src/net`·`src/game/Room*`을 tokio로 옮긴 것이다.
//!
//! 태스크 구조
//! ```text
//! tokio 런타임 (스레드 N개)
//!  ├─ 세션 태스크 2개 (연결마다)   읽기 → 패킷 해석 → 방에 명령 전송 / 쓰기 대기열 → 소켓
//!  └─ 방 태스크 (층마다 하나)      명령(입장·퇴장·입력…) 처리 → 20Hz 틱: 몬스터·검기, 공격 판정, 상태 브로드캐스트
//! 로그 스레드 (하나)               대기열에 쌓인 줄을 출력. 게임 틱은 출력을 기다리지 않는다
//! ```
//! - 방의 상태는 방 태스크 하나만 가지므로 락이 없다. 다른 태스크는 채널로 명령을 보낸다(C++ 서버의 strand와 같은 역할).
//! - 서로 다른 방은 다른 태스크라서 여러 스레드에서 동시에 돌아간다.
//! - 락은 `RoomManager` 한 곳뿐이다. 정원 확인을 뮤텍스 안에서 끝낸다.

